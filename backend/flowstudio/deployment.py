"""Generate immutable per-process Python modules and atomically activate them."""

import hashlib
import json
import os
import pprint
import secrets
from pathlib import Path

from .models import Flow, Fault
from .generation import canonical
from .storage import timestamp
from .validation import require_valid


def signature(flow: Flow, project: dict, databases: list) -> str:
    return hashlib.sha256(
        canonical(
            {
                "flow": flow.model_dump(by_alias=True, exclude={"ui"}),
                "databases": [
                    d.model_dump() for d in databases if d.id in project["databaseIds"]
                ],
                "projectDatabases": sorted(project["databaseIds"]),
            }
        )
    ).hexdigest()


class Deployments:
    def __init__(self, store):
        self.store = store
        self.root = store.path.parent / "generated"
        with store.connection() as c:
            c.execute("""CREATE TABLE IF NOT EXISTS applied_processes(
                process_id TEXT PRIMARY KEY REFERENCES processes(id),
                build_hash TEXT NOT NULL, flow TEXT NOT NULL,
                source_path TEXT NOT NULL, applied_at TEXT NOT NULL)""")

    def apply(self, process: dict, flow: Flow) -> dict:
        value = flow.model_dump(by_alias=True)
        value.pop("ui", None)
        literal = pprint.pformat(value, sort_dicts=True, width=100)
        source = (
            "# Generated by Flow Studio. Edit the process in the designer.\n"
            "from flowstudio.models import Flow\n\n"
            f"PROCESS_ID = {flow.id!r}\n"
            f"FLOW = Flow.model_validate({literal})\n\n"
            "def execute(engine, input_):\n"
            "    return engine.run(FLOW, input_, preview=False)\n"
        )
        compile(source, "process.py", "exec")
        digest = hashlib.sha256(source.encode()).hexdigest()
        # The identifier comes from the database, never from a client path.
        target = self.root / process["id"] / digest
        target.mkdir(parents=True, exist_ok=True)
        source_path = target / "process.py"
        for name, content in {
            "process.py": source.encode(),
            "flow.json": canonical(value),
        }.items():
            temp = target / (name + "." + secrets.token_hex(8) + ".tmp")
            try:
                temp.write_bytes(content)
                os.replace(temp, target / name)
            finally:
                temp.unlink(missing_ok=True)
        with self.store.connection() as c:
            previous = c.execute(
                "SELECT build_hash, flow FROM applied_processes WHERE process_id=?",
                (process["id"],),
            ).fetchone()
            old = json.loads(previous["flow"]) if previous else {}
            before = {n["id"]: n for n in old.get("nodes", [])}
            after = {n["id"]: n for n in value["nodes"]}
            changes = {
                "addedNodes": sorted(after.keys() - before.keys()),
                "removedNodes": sorted(before.keys() - after.keys()),
                "changedNodes": sorted(
                    k for k in after.keys() & before.keys() if after[k] != before[k]
                ),
                "connectionsChanged": old.get("edges", []) != value["edges"],
            }
            at = timestamp()
            c.execute(
                """INSERT INTO applied_processes VALUES(?,?,?,?,?)
                ON CONFLICT(process_id) DO UPDATE SET build_hash=excluded.build_hash,
                flow=excluded.flow,source_path=excluded.source_path,applied_at=excluded.applied_at""",
                (
                    process["id"],
                    digest,
                    canonical(value).decode(),
                    str(source_path),
                    at,
                ),
            )
        return {
            "processId": flow.id,
            "buildHash": digest,
            "sourcePath": str(source_path),
            "appliedAt": at,
            "changed": not previous or previous["build_hash"] != digest,
            "changes": changes,
        }

    def execute(self, id_, engine, input_):
        with self.store.connection() as c:
            row = c.execute(
                "SELECT source_path,build_hash FROM applied_processes WHERE process_id=?",
                (id_,),
            ).fetchone()
        if not row:
            raise Fault("NOT_APPLIED", "먼저 구성 검증 후 서버에 반영하세요.", 409)
        source = Path(row["source_path"]).read_bytes()
        if hashlib.sha256(source).hexdigest() != row["build_hash"]:
            raise Fault(
                "BUILD_MISMATCH",
                "반영된 코드가 변경되었습니다. 다시 서버에 반영하세요.",
                409,
            )
        namespace = {}
        exec(compile(source, row["source_path"], "exec"), namespace)
        require_valid(
            namespace["FLOW"], set(self.store.process(id_)["project"]["databaseIds"])
        )
        return namespace["execute"](engine, input_)
