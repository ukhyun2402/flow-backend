test('blank canvas closes settings and applying a node preserves the viewport',async({page})=>{
  await page.goto('/');
  const iframe=page.frameLocator('iframe[title="draw.io 프로세스 편집기"]');
  const node=iframe.getByText('HTTP 요청',{exact:false}).first();
  await node.waitFor();
  const frame=page.frames().find(f=>f.url().includes('/drawio/index.html'));
  await frame.evaluate(()=>{
    const previous=mxGraph.prototype.fireEvent;
    mxGraph.prototype.fireEvent=function(...args){if(this.container===document.querySelector('.geDiagramContainer'))window.__testGraph=this;return previous.apply(this,args);};
  });
  await node.click();
  const panel=page.locator('.node-inspector');
  await expect(panel).toBeVisible();
  await iframe.locator('.geDiagramContainer').click({position:{x:700,y:450}});
  await expect(panel).toBeHidden();
  await node.click();
  await expect(panel).toBeVisible();
  await frame.evaluate(()=>{window.__testGraph.view.scaleAndTranslate(.8,150,90);});
  const before=await node.boundingBox();
  await panel.getByLabel('표시 이름',{exact:true}).fill('위치 유지 확인');
  await panel.getByRole('button',{name:'설정 적용',exact:true}).click();
  const renamed=iframe.getByText('위치 유지 확인',{exact:false}).first();
  await expect(renamed).toBeVisible();
  await expect.poll(async()=>{const after=await renamed.boundingBox();return Math.abs(after.x+after.width/2-before.x-before.width/2);}).toBeLessThan(3);
  expect(Math.abs((await renamed.boundingBox()).y-before.y)).toBeLessThan(3);
  expect(await frame.evaluate(()=>window.__testGraph.view.scale)).toBeCloseTo(.8,4);
  await expect(panel).toBeVisible();
});

