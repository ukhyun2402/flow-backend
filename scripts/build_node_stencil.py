"""Generate a native draw.io stencil for the five-point validation shield."""

import base64
import zlib
from pathlib import Path
from urllib.parse import quote

xml = """<shape w="100" h="100" aspect="variable" strokewidth="inherit">
<connections><constraint x="0" y="0.5" perimeter="1"/><constraint x="1" y="0.5" perimeter="1"/></connections>
<background><path><move x="0" y="0"/><line x="100" y="0"/><line x="100" y="60"/><line x="50" y="100"/><line x="0" y="60"/><close/></path></background>
<foreground><fillstroke/></foreground></shape>"""
compressor = zlib.compressobj(wbits=-15)
value = base64.b64encode(
    compressor.compress(quote(xml, safe="").encode()) + compressor.flush()
).decode()
Path(__file__).resolve().parents[1].joinpath("frontend/src/stencils.ts").write_text(
    "// Generated by scripts/build_node_stencil.py\nexport const validationShield = "
    + repr(value)
    + ";\n",
    encoding="utf-8",
)
